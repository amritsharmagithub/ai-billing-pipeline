# Builds the reconciliation report as a Markdown file: reports/reconciliation_report.md
# Reads the dbt models from the DuckDB database (read-only), so run `dbt build` first.
# Run from the project folder: python -m reports.build_reconciliation_report

from pathlib import Path

import duckdb

from generator.config import REPORT_DATE
from generator.db import DB_PATH

OUTPUT_PATH = Path("reports/reconciliation_report.md")

# Plain-English names for each break type, in the order they appear in the report.
BREAK_NAMES = {
    "unapplied_cash": "Unapplied cash",
    "duplicate_payment": "Duplicate payment",
    "short_payment_wire_fee": "Short payment (wire fee)",
    "short_payment_unexplained": "Short payment (unexplained)",
    "unbilled_usage_missing_invoice": "Missing invoice (unbilled usage)",
    "unbilled_usage_understated": "Understated usage on invoice",
    "invoice_math_error": "Invoice math error",
    "cutoff_error": "Month-end cutoff error",
    "aged_90_plus": "Aged 90+ days (collections)",
}

# The general action for each break type (the details section has the action for each record).
BREAK_ACTIONS = {
    "unapplied_cash": "Apply each payment to its matching invoice.",
    "duplicate_payment": "Refund the customer, or hold the amount as a credit.",
    "short_payment_wire_fee": "Write off the $25.00 bank fee.",
    "short_payment_unexplained": "Contact the customer to collect the difference.",
    "unbilled_usage_missing_invoice": "Create and send the missing invoice.",
    "unbilled_usage_understated": "Bill the difference.",
    "invoice_math_error": "Correct the invoice and bill the difference.",
    "cutoff_error": "Check the received date against the bank statement and correct the posting date.",
    "aged_90_plus": "Collections follow-up, or review for write-off.",
}


def money(amount):
    """Format a number as dollars, for example 1234.5 -> $1,234.50."""
    if amount < 0:
        return f"-${abs(amount):,.2f}"
    return f"${amount:,.2f}"


def markdown_table(headers, rows):
    """Turn a header list and a list of rows into a Markdown table."""
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for row in rows:
        lines.append("| " + " | ".join(str(value) for value in row) + " |")
    return "\n".join(lines)


def main():
    con = duckdb.connect(str(DB_PATH), read_only=True)

    # Accounts receivable tie-out: billed - applied payments - unapplied cash = net balance.
    billed, applied, balance = con.execute("""
        select sum(total_usd), sum(amount_paid_usd), sum(balance_due_usd)
        from main_marts.fct_invoices
    """).fetchone()
    unapplied = con.execute(
        "select coalesce(sum(amount_usd), 0) from main_staging.stg_payments where invoice_id is null"
    ).fetchone()[0]
    collected = con.execute("select sum(amount_usd) from main_staging.stg_payments").fetchone()[0]

    breaks = con.execute("""
        select break_type, record_id, customer_id, amount_usd, details, suggested_action,
               debit_account, credit_account
        from main_reports.rpt_reconciliation_breaks
    """).fetchall()

    answer_key = con.execute("""
        select error_type, planted, found, missed, extra_breaks
        from main_reports.rpt_reconciliation_vs_answer_key
    """).fetchall()

    aging = con.execute("""
        select aging_bucket, count(*), sum(balance_due_usd)
        from main_marts.fct_invoices
        group by aging_bucket
    """).fetchall()

    con.close()

    # --- Build the report, section by section ---
    order = list(BREAK_NAMES)
    lines = []

    lines.append("# Lumen AI: Billing Reconciliation Report")
    lines.append("")
    lines.append(f"**As of:** {REPORT_DATE:%B %d, %Y} (month-end close)  ")
    lines.append("**Source:** dbt models `rpt_reconciliation_breaks` and `fct_invoices`. "
                 "Generated by `reports/build_reconciliation_report.py`.")
    lines.append("")

    # 1. Summary
    planted = sum(row[1] for row in answer_key)
    found = sum(row[2] for row in answer_key)
    missed = sum(row[3] for row in answer_key)
    extra = sum(row[4] for row in answer_key)
    error_breaks = [b for b in breaks if b[0] != "aged_90_plus"]
    aged = [b for b in breaks if b[0] == "aged_90_plus"]

    lines.append("## 1. Summary")
    lines.append("")
    lines.append(f"- **{len(error_breaks)} breaks** found by the reconciliation rules, "
                 f"totaling **{money(sum(b[3] for b in error_breaks))}**.")
    lines.append(f"- **{len(aged)} invoices** aged 90+ days, with **{money(sum(b[3] for b in aged))}** "
                 "still owed (collections follow-up).")
    lines.append(f"- **Check against the planted errors:** {found} of {planted} found, "
                 f"{missed} missed, {extra} extra.")
    lines.append("")

    # 2. Accounts receivable tie-out
    lines.append("## 2. Accounts receivable tie-out")
    lines.append("")
    lines.append(markdown_table(
        ["Line", "Amount"],
        [
            ["Total billed", money(billed)],
            ["Less: payments applied to invoices", money(-applied)],
            ["= Open balance on invoices", money(balance)],
            ["Less: unapplied cash (received, not yet matched)", money(-unapplied)],
            ["= Net amount still owed by customers", money(balance - unapplied)],
        ],
    ))
    lines.append("")
    check = "ties out" if billed - collected == balance - unapplied else "DOES NOT tie out"
    lines.append(f"Check: total billed ({money(billed)}) minus total collected ({money(collected)}) "
                 f"= {money(billed - collected)}, which **{check}** to the net amount owed.")
    lines.append("")

    # 3. Breaks by type
    lines.append("## 3. Breaks by type")
    lines.append("")
    summary_rows = []
    for break_type in order:
        of_type = [b for b in breaks if b[0] == break_type]
        if of_type:
            summary_rows.append([BREAK_NAMES[break_type], len(of_type),
                                 money(sum(b[3] for b in of_type)), BREAK_ACTIONS[break_type]])
    lines.append(markdown_table(["Break", "Count", "Amount", "Suggested action"], summary_rows))
    lines.append("")

    # 4. Suggested journal entries, totaled by account pair
    lines.append("## 4. Suggested journal entries")
    lines.append("")
    lines.append("Totals by debit and credit account. Unexplained short payments have no entry "
                 "until the customer responds.")
    lines.append("")
    entries = {}
    for b in breaks:
        if b[6]:
            key = (b[6], b[7])
            entries[key] = entries.get(key, 0) + b[3]
    entry_rows = [[debit, credit, money(amount)]
                  for (debit, credit), amount in sorted(entries.items(), key=lambda e: -e[1])]
    lines.append(markdown_table(["Debit", "Credit", "Amount"], entry_rows))
    lines.append("")

    # 5. Break details
    lines.append("## 5. Break details")
    lines.append("")
    for break_type in order:
        of_type = sorted([b for b in breaks if b[0] == break_type], key=lambda b: b[1])
        if not of_type:
            continue
        lines.append(f"### {BREAK_NAMES[break_type]}")
        lines.append("")
        lines.append(markdown_table(
            ["Record", "Customer", "Amount", "Details", "Action", "Journal entry"],
            [[b[1], b[2], money(b[3]), b[4], b[5], f"Dr {b[6]} / Cr {b[7]}" if b[6] else "None yet"]
             for b in of_type],
        ))
        lines.append("")

    # 6. Aging
    lines.append("## 6. Aging of invoice balances")
    lines.append("")
    bucket_order = ["current", "1-30", "31-60", "61-90", "90+", "credit_balance", "settled"]
    aging_by_bucket = {row[0]: row for row in aging}
    lines.append(markdown_table(
        ["Aging bucket", "Invoices", "Balance"],
        [[bucket, aging_by_bucket[bucket][1], money(aging_by_bucket[bucket][2])]
         for bucket in bucket_order if bucket in aging_by_bucket],
    ))
    lines.append("")
    if "90+" in aging_by_bucket and aging_by_bucket["90+"][1] != len(aged):
        lines.append(f"Note: {aging_by_bucket['90+'][1]} invoices are 90+ days past due, but only {len(aged)} "
                     "are listed as collections items in section 3. The others are already covered by "
                     "another break (a short payment, or unapplied cash that matches the invoice), "
                     "so each problem is counted once.")
        lines.append("")

    # 7. Answer key check
    lines.append("## 7. Check against the planted errors")
    lines.append("")
    lines.append("The data has 20 errors planted on purpose (see `generator/errors.py`). "
                 "The rules above never read the answer key; this table compares their results with it.")
    lines.append("")
    lines.append(markdown_table(
        ["Error type", "Planted", "Found", "Missed", "Extra"],
        [[BREAK_NAMES[row[0]], row[1], row[2], row[3], row[4]] for row in answer_key],
    ))
    lines.append("")

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text("\n".join(lines))
    print(f"Wrote {OUTPUT_PATH} ({len(breaks)} breaks, {found} of {planted} planted errors found)")


if __name__ == "__main__":
    main()
